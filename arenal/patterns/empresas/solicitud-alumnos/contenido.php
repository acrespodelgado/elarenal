            <div class="col col-12">
                <p>La Ley Orgánica 3/2022, de 31 de marzo, de Ordenación e Integración de la Formación Profesional incorpora un sistema de Formación profesional Dual, que se lleva a cabo armonizando los procesos de enseñanza y aprendizaje entre el centro de formación profesional y la empresa u organismo equiparado, en corresponsabilidad entre ambos agentes, con la finalidad de la mejora de la empleabilidad de la persona en formación.</p>
                <ul>
                    <li>Toda la Formación Profesional de Grado D (Ciclo Formativo de Grado Básico, Medio y Superior) incorporarán una fase de formación en empresa u organismo equiparado, en 1º y en 2º.</li>
                    <li>Tanto en el centro educativo como en la empresa u organismo equiparado, se pueden desarrollar aprendizajes de todos los módulos profesionales.</li>
                    <li>Se cumplirá con un Plan de formación inicial y un Plan de formación individual.</li>
                </ul>
            </div>
            <div class="col col-12 mt-3">
                <h3><span class="accent">REQUISITOS</span> DEL ALUMNADO</h3>
                <ul>
                    <li>Tener cumplidos los 16 años.</li>
                    <li>Haber superado la adquisición de las competencias relativas a los riesgos específicos y la prevención de riesgos laborales.</li>
                    <li>Será dado de alta en el sistema de la Seguridad Social (en principio, por parte de Consejería de Formación Profesional y Desarrollo Educativo).</li>
                </ul>
                <h3><span class="accent">REQUISITOS</span> DE LAS EMPRESAS U ORGANISMOS EQUIPARADOS</h3>
                <ul>
                    <li>Cualquier empresa u organismo equiparado podrá participar en esta fase.</li>
                    <li>No podrá existir relación contractual entre la empresa u organismo equiparado y el alumno o alumna.</li>
                    <li>Se asignará un tutor laboral por parte de la empresa para hacer el seguimiento del alumnado.</li>
                </ul>
                <h3>DURACIÓN Y PERIODO DE REALIZACIÓN</h3>
                <h4><strong>Grado Básico</strong></h4>
                <ul>
                    <li>El 20% de la duración total del ciclo formativo (400 horas).</li>
                    <li>1er curso: 3er trimestre, hasta completar 105 horas, 3 días a la semana.</li>
                    <li>2º curso: 2º-3er trimestre, hasta completar 295 horas, 3 días a la semana.</li>
                </ul>
                <h4><strong>Grado Medio y Superior</strong></h4>
                <ul>
                    <li>El 25% del total previsto del ciclo formativo (500 horas).</li>
                    <li>1er curso: 2º trimestre, hasta completar 126 horas, 5 días a la semana.</li>
                    <li>2º curso (a excepción del CFGM de Mantenimiento Electromecánico): 2º-3er trimestre, hasta completar 374 horas, 4 días a la semana.</li>
                </ul>
